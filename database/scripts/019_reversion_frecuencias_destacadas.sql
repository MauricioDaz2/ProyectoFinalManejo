-- RFC-000085: reversión de 019_frecuencias_destacadas.sql. Idempotente y transaccional.
-- Elimina el trigger, el índice, las restricciones y las columnas LIM_DES_COP / ES_DESTACADA.
SET XACT_ABORT ON;
BEGIN TRY
    BEGIN TRANSACTION;

    IF OBJECT_ID('dbo.TR_RFC085_CupoDestacadas', 'TR') IS NOT NULL
        DROP TRIGGER dbo.TR_RFC085_CupoDestacadas;

    IF EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID('dbo.FRECUENCIAS') AND name = 'IX_FRECUENCIAS_DESTACADAS')
        DROP INDEX IX_FRECUENCIAS_DESTACADAS ON dbo.FRECUENCIAS;

    IF OBJECT_ID('dbo.DF_FRECUENCIAS_ES_DESTACADA', 'D') IS NOT NULL
        ALTER TABLE dbo.FRECUENCIAS DROP CONSTRAINT DF_FRECUENCIAS_ES_DESTACADA;
    IF COL_LENGTH('dbo.FRECUENCIAS', 'ES_DESTACADA') IS NOT NULL
        ALTER TABLE dbo.FRECUENCIAS DROP COLUMN ES_DESTACADA;

    IF OBJECT_ID('dbo.CK_COOPERATIVAS_LIM_DES_COP', 'C') IS NOT NULL
        ALTER TABLE dbo.COOPERATIVAS DROP CONSTRAINT CK_COOPERATIVAS_LIM_DES_COP;
    IF OBJECT_ID('dbo.DF_COOPERATIVAS_LIM_DES_COP', 'D') IS NOT NULL
        ALTER TABLE dbo.COOPERATIVAS DROP CONSTRAINT DF_COOPERATIVAS_LIM_DES_COP;
    IF COL_LENGTH('dbo.COOPERATIVAS', 'LIM_DES_COP') IS NOT NULL
        ALTER TABLE dbo.COOPERATIVAS DROP COLUMN LIM_DES_COP;

    COMMIT TRANSACTION;
    PRINT 'RFC-000085: reversión 019 aplicada.';
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;
