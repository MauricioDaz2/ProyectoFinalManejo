SET XACT_ABORT ON;
BEGIN TRANSACTION;
IF OBJECT_ID('dbo.GRUPOS_PROGRAMACION','U') IS NULL
BEGIN
    CREATE TABLE dbo.GRUPOS_PROGRAMACION (
        ID_GRU int IDENTITY PRIMARY KEY,
        ID_COP varchar(5) NOT NULL REFERENCES dbo.COOPERATIVAS(ID_COP),
        TIPO varchar(12) NOT NULL CHECK(TIPO IN ('BUS','FRECUENCIA')),
        NOMBRE nvarchar(80) NOT NULL,
        CONSTRAINT UQ_GRUPOS_PROGRAMACION_NOMBRE UNIQUE(ID_COP,TIPO,NOMBRE)
    );
    CREATE TABLE dbo.GRUPO_BUSES (
        ID_BUS varchar(5) NOT NULL PRIMARY KEY REFERENCES dbo.BUSES(ID_BUS),
        ID_GRU int NOT NULL REFERENCES dbo.GRUPOS_PROGRAMACION(ID_GRU) ON DELETE CASCADE,
        ORDEN int NOT NULL,
        UNIQUE(ID_GRU,ORDEN)
    );
    CREATE TABLE dbo.GRUPO_FRECUENCIAS (
        ID_GRU int NOT NULL REFERENCES dbo.GRUPOS_PROGRAMACION(ID_GRU) ON DELETE CASCADE,
        ID_FRE varchar(5) NOT NULL REFERENCES dbo.FRECUENCIAS(ID_FRE),
        ORDEN int NOT NULL,
        PRIMARY KEY(ID_GRU,ID_FRE),
        UNIQUE(ID_GRU,ORDEN)
    );
END;
COMMIT;
GO
