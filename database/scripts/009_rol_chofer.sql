USE BD_COOPERATIVAS_BUSES;
GO

SET XACT_ABORT ON;
BEGIN TRY
    BEGIN TRANSACTION;
    IF NOT EXISTS (SELECT 1 FROM dbo.ROLES WITH (UPDLOCK, HOLDLOCK) WHERE ID_ROL = 'R006')
        INSERT INTO dbo.ROLES (ID_ROL, NOM_ROL) VALUES ('R006', 'Chofer');
    ELSE IF EXISTS (SELECT 1 FROM dbo.ROLES WHERE ID_ROL = 'R006' AND LTRIM(RTRIM(NOM_ROL)) <> 'Chofer')
        THROW 51000, 'R006 ya existe con otro nombre. Revisa el registro antes de continuar.', 1;
    COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;
