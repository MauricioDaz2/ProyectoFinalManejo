SET XACT_ABORT ON;
BEGIN TRY
    BEGIN TRANSACTION;
    IF OBJECT_ID('dbo.COOPERATIVA_IMAGENES', 'U') IS NULL
        THROW 51000, 'Instale primero 003_cooperativa_perfiles.sql en la base de datos del proyecto.', 1;

    IF EXISTS (SELECT 1 FROM sys.check_constraints WHERE parent_object_id = OBJECT_ID('dbo.COOPERATIVA_IMAGENES') AND name = 'CK_IMAGEN_MIME')
        ALTER TABLE dbo.COOPERATIVA_IMAGENES DROP CONSTRAINT CK_IMAGEN_MIME;
    ALTER TABLE dbo.COOPERATIVA_IMAGENES WITH CHECK ADD CONSTRAINT CK_IMAGEN_MIME
        CHECK (MIME IN ('image/jpeg', 'image/png', 'image/webp'));

    IF EXISTS (SELECT 1 FROM sys.check_constraints WHERE parent_object_id = OBJECT_ID('dbo.COOPERATIVA_IMAGENES') AND name = 'CK_IMAGEN_DIMENSIONES')
        ALTER TABLE dbo.COOPERATIVA_IMAGENES DROP CONSTRAINT CK_IMAGEN_DIMENSIONES;
    ALTER TABLE dbo.COOPERATIVA_IMAGENES WITH CHECK ADD CONSTRAINT CK_IMAGEN_DIMENSIONES
        CHECK (ANCHO BETWEEN 1 AND 32768 AND ALTO BETWEEN 1 AND 32768
            AND CAST(ANCHO AS bigint) * ALTO <= 24000000 AND BYTES > 0);
    COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;
