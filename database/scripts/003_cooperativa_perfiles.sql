USE BD_COOPERATIVAS_BUSES;
GO

SET XACT_ABORT ON;
BEGIN TRY
    BEGIN TRANSACTION;
    IF OBJECT_ID('dbo.COOPERATIVAS', 'U') IS NULL
        THROW 51000, 'No existe dbo.COOPERATIVAS. Seleccione la base de datos del proyecto.', 1;

    IF OBJECT_ID('dbo.COOPERATIVA_PERFILES', 'U') IS NULL
    BEGIN
        CREATE TABLE dbo.COOPERATIVA_PERFILES (
            ID_COP varchar(5) NOT NULL CONSTRAINT PK_COOPERATIVA_PERFILES PRIMARY KEY,
            BORRADOR_JSON nvarchar(max) NOT NULL,
            PUBLICADO_JSON nvarchar(max) NULL,
            REVISION int NOT NULL CONSTRAINT DF_PERFIL_REVISION DEFAULT (1),
            ACTUALIZADO_UTC datetime2(3) NOT NULL CONSTRAINT DF_PERFIL_ACTUALIZADO DEFAULT SYSUTCDATETIME(),
            PUBLICADO_UTC datetime2(3) NULL,
            CONSTRAINT FK_PERFIL_COOPERATIVA FOREIGN KEY (ID_COP) REFERENCES dbo.COOPERATIVAS(ID_COP),
            CONSTRAINT CK_PERFIL_BORRADOR_JSON CHECK (ISJSON(BORRADOR_JSON) = 1),
            CONSTRAINT CK_PERFIL_PUBLICADO_JSON CHECK (PUBLICADO_JSON IS NULL OR ISJSON(PUBLICADO_JSON) = 1),
            CONSTRAINT CK_PERFIL_REVISION CHECK (REVISION > 0)
        );
    END;

    IF OBJECT_ID('dbo.COOPERATIVA_IMAGENES', 'U') IS NULL
    BEGIN
        CREATE TABLE dbo.COOPERATIVA_IMAGENES (
            ID_IMG uniqueidentifier NOT NULL CONSTRAINT PK_COOPERATIVA_IMAGENES PRIMARY KEY,
            ID_COP varchar(5) NOT NULL,
            TIPO varchar(10) NOT NULL,
            ARCHIVO varchar(50) NOT NULL CONSTRAINT UQ_IMAGEN_ARCHIVO UNIQUE,
            MIME varchar(20) NOT NULL,
            BYTES int NOT NULL,
            ANCHO int NOT NULL,
            ALTO int NOT NULL,
            CREADO_UTC datetime2(3) NOT NULL CONSTRAINT DF_IMAGEN_CREADO DEFAULT SYSUTCDATETIME(),
            CONSTRAINT FK_IMAGEN_COOPERATIVA FOREIGN KEY (ID_COP) REFERENCES dbo.COOPERATIVAS(ID_COP),
            CONSTRAINT CK_IMAGEN_TIPO CHECK (TIPO IN ('logo', 'portada', 'galeria')),
            CONSTRAINT CK_IMAGEN_MIME CHECK (MIME = 'image/webp'),
            CONSTRAINT CK_IMAGEN_DIMENSIONES CHECK (ANCHO BETWEEN 64 AND 6000 AND ALTO BETWEEN 64 AND 6000 AND BYTES > 0)
        );
        CREATE INDEX IX_IMAGEN_COOPERATIVA ON dbo.COOPERATIVA_IMAGENES(ID_COP, CREADO_UTC);
    END;
    COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;
