BEGIN TRANSACTION;
IF EXISTS (SELECT 1 FROM dbo.USUARIOS GROUP BY LOWER(LTRIM(RTRIM(COR_USU))) HAVING COUNT(*) > 1)
    THROW 51000, 'Existen correos duplicados. Resolverlos antes de instalar, sin eliminar cuentas.', 1;
IF COL_LENGTH('dbo.USUARIOS', 'COR_ACCESO_NORMALIZADO') IS NULL
    ALTER TABLE dbo.USUARIOS ADD COR_ACCESO_NORMALIZADO AS LOWER(LTRIM(RTRIM(COR_USU))) PERSISTED;
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID('dbo.USUARIOS') AND name = 'UX_USUARIOS_CORREO_ACCESO')
    EXEC('CREATE UNIQUE INDEX UX_USUARIOS_CORREO_ACCESO ON dbo.USUARIOS(COR_ACCESO_NORMALIZADO)');
IF OBJECT_ID('dbo.COOPERATIVA_RESPONSABLES', 'U') IS NULL
    CREATE TABLE dbo.COOPERATIVA_RESPONSABLES (
        ID_COP varchar(5) NOT NULL PRIMARY KEY REFERENCES dbo.COOPERATIVAS(ID_COP),
        ID_USU varchar(10) NOT NULL UNIQUE REFERENCES dbo.USUARIOS(ID_USU),
        DESIGNADO_POR varchar(10) NOT NULL REFERENCES dbo.USUARIOS(ID_USU),
        DESIGNADO_UTC datetime2 NOT NULL DEFAULT SYSUTCDATETIME()
    );
IF OBJECT_ID('dbo.USUARIO_PERMISOS', 'U') IS NULL
    CREATE TABLE dbo.USUARIO_PERMISOS (
        ID_USU varchar(10) NOT NULL REFERENCES dbo.USUARIOS(ID_USU),
        PERMISO varchar(24) NOT NULL CHECK (PERMISO IN ('dashboard','buses','rutas','resoluciones','salidas','reportes','personalizacion','trabajadores')),
        CONSTRAINT PK_USUARIO_PERMISOS PRIMARY KEY (ID_USU, PERMISO)
    );
IF OBJECT_ID('dbo.USUARIO_FOTOGRAFIAS', 'U') IS NULL
    CREATE TABLE dbo.USUARIO_FOTOGRAFIAS (
        ID_USU varchar(10) NOT NULL PRIMARY KEY REFERENCES dbo.USUARIOS(ID_USU),
        CONTENIDO varbinary(max) NOT NULL CHECK (DATALENGTH(CONTENIDO) BETWEEN 1 AND 8388608),
        MIME varchar(20) NOT NULL CHECK (MIME IN ('image/jpeg','image/png','image/webp')),
        VERSION uniqueidentifier NOT NULL DEFAULT NEWID(),
        ACTUALIZADO_UTC datetime2 NOT NULL DEFAULT SYSUTCDATETIME()
    );
EXEC('CREATE OR ALTER TRIGGER dbo.TR_RESPONSABLE_VALIDO ON dbo.COOPERATIVA_RESPONSABLES AFTER INSERT, UPDATE, DELETE AS
BEGIN
 SET NOCOUNT ON;
 IF EXISTS (SELECT 1 FROM deleted D WHERE NOT EXISTS (SELECT 1 FROM dbo.COOPERATIVA_RESPONSABLES R WHERE R.ID_COP=D.ID_COP))
   THROW 51000, ''Reemplaza al responsable; no retires la designación.'', 1;
 IF EXISTS (SELECT 1 FROM inserted R JOIN dbo.USUARIOS U ON U.ID_USU=R.ID_USU JOIN dbo.USUARIOS A ON A.ID_USU=R.DESIGNADO_POR
 WHERE U.ID_ROL_PER<>''R002'' OR U.EST_USU<>''1'' OR U.ID_COP_PER IS NULL OR U.ID_COP_PER<>R.ID_COP OR A.ID_ROL_PER<>''R001'' OR A.EST_USU<>''1'')
   THROW 51000, ''El responsable debe ser un R002 activo de la cooperativa y ser designado por R001.'', 1;
END');
EXEC('CREATE OR ALTER TRIGGER dbo.TR_PROTEGER_RESPONSABLE ON dbo.USUARIOS AFTER UPDATE AS
BEGIN
 SET NOCOUNT ON;
 IF EXISTS (SELECT 1 FROM inserted U JOIN dbo.COOPERATIVA_RESPONSABLES R ON R.ID_USU=U.ID_USU
 WHERE U.ID_ROL_PER<>''R002'' OR U.EST_USU<>''1'' OR U.ID_COP_PER IS NULL OR U.ID_COP_PER<>R.ID_COP)
   THROW 51000, ''Designa primero otro responsable principal activo.'', 1;
END');
COMMIT;
