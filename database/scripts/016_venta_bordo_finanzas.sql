SET XACT_ABORT ON;
BEGIN TRANSACTION;
IF EXISTS (SELECT 1 FROM sys.columns WHERE object_id=OBJECT_ID('dbo.BOLETOS') AND name='PRE_FIN_BOL' AND scale=0)
    ALTER TABLE dbo.BOLETOS ALTER COLUMN PRE_FIN_BOL decimal(20,2) NOT NULL;

IF OBJECT_ID('dbo.HOJA_GASTOS','U') IS NULL
BEGIN
    CREATE TABLE dbo.HOJA_GASTOS (
        ID_GAS uniqueidentifier NOT NULL PRIMARY KEY,
        ID_HOJ varchar(5) NOT NULL REFERENCES dbo.HOJAS_RUTAS(ID_HOJ),
        ID_USU varchar(10) NOT NULL REFERENCES dbo.USUARIOS(ID_USU),
        CATEGORIA varchar(15) NOT NULL CHECK (CATEGORIA IN ('COMBUSTIBLE','ALIMENTACION','PEAJE','HOSPEDAJE','OTROS')),
        MONTO decimal(10,2) NOT NULL CHECK (MONTO > 0),
        DETALLE nvarchar(200) NULL,
        FECHA_UTC datetime2 NOT NULL DEFAULT SYSUTCDATETIME()
    );
    CREATE INDEX IX_HOJA_GASTOS_HOJA ON dbo.HOJA_GASTOS(ID_HOJ, FECHA_UTC);
END;

IF OBJECT_ID('dbo.HOJA_VENTAS_BORDO','U') IS NULL
BEGIN
    CREATE TABLE dbo.HOJA_VENTAS_BORDO (
        ID_OPERACION uniqueidentifier NOT NULL PRIMARY KEY,
        ID_BOL varchar(5) NOT NULL UNIQUE REFERENCES dbo.BOLETOS(ID_BOL),
        ID_USU varchar(10) NOT NULL REFERENCES dbo.USUARIOS(ID_USU),
        EFECTIVO decimal(10,2) NOT NULL,
        VUELTO decimal(10,2) NOT NULL
    );
END;
COMMIT;
GO
