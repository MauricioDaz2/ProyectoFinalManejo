IF COL_LENGTH('dbo.USUARIOS', 'CED_USU') IS NULL
BEGIN
    ALTER TABLE dbo.USUARIOS ADD CED_USU varchar(10) NULL;
END;
GO

IF NOT EXISTS (
    SELECT 1
    FROM sys.indexes
    WHERE name = 'UX_USUARIOS_CED_USU'
      AND object_id = OBJECT_ID('dbo.USUARIOS')
)
BEGIN
    CREATE UNIQUE INDEX UX_USUARIOS_CED_USU
        ON dbo.USUARIOS (CED_USU)
        WHERE CED_USU IS NOT NULL;
END;
GO

UPDATE dbo.USUARIOS
SET CED_USU = '1712345678'
WHERE ID_USU = 'USUFINAL1'
  AND (CED_USU IS NULL OR CED_USU <> '1712345678');
GO
