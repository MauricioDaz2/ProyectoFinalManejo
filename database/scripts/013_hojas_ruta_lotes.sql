        ALTER TABLE dbo.HOJAS_RUTAS ADD CONSTRAINT CK_CC02_TRIPULANTES CHECK (
            EST_VIA_HOJ NOT IN ('PROGRAMADO','PROGRAMADA','EN CURSO') OR ID_USU_CHO<>ID_USU_CON
        );
    IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID('dbo.HOJAS_RUTAS') AND name='IX_CC02_HOJ_CHO')
